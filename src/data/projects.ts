/** Verb on the primary link, by type. Archived work never gets a sales verb. */
export function primaryAction(entry: ProjectEntry): string {
  if (entry.status === "archived" || entry.status === "sold") return "View archive";
  if (entry.type.includes("community")) return "Join";
  if (entry.type.includes("book")) return "Read";
  if (entry.type.includes("app") || entry.type.includes("tool")) return "Try";
  return "Visit";
}

